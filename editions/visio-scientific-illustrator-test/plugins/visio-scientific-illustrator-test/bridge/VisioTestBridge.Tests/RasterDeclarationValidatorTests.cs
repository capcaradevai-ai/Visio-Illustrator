using System.Security.Cryptography;
using VisioTestBridge.Contracts;
using VisioTestBridge.Core;
using VisioTestBridge.Core.Assets;

namespace VisioTestBridge.Tests;

public sealed class RasterDeclarationValidatorTests : IDisposable
{
    private readonly string _path = Path.Combine(
        Path.GetTempPath(),
        $"vsi-test-raster-{Guid.NewGuid():N}.png");

    public RasterDeclarationValidatorTests()
    {
        File.WriteAllBytes(_path, [1, 2, 3, 4, 5]);
    }

    [Fact]
    public void Accepts_atomic_user_file_with_matching_hash()
    {
        var declaration = Valid("user_file");

        var result = RasterDeclarationValidator.Validate(
            _path,
            new PixelBox(0, 0, 64, 64),
            declaration);

        Assert.Equal(declaration.AssetId, result.AssetId);
        Assert.Equal(declaration.AssetSha256, result.AssetSha256);
    }

    [Theory]
    [InlineData(false, false)]
    [InlineData(true, true)]
    public void Rejects_non_atomic_or_reconstructable_raster(
        bool atomicRasterUnit,
        bool containsReconstructableContent)
    {
        var declaration = Valid("user_file") with
        {
            AtomicRasterUnit = atomicRasterUnit,
            ContainsReconstructableContent = containsReconstructableContent,
        };

        var error = Assert.Throws<BridgeCommandException>(() =>
            RasterDeclarationValidator.Validate(
                _path,
                new PixelBox(0, 0, 64, 64),
                declaration));

        Assert.Equal(BridgeErrorCodes.RasterDeclarationInvalid, error.Code);
    }

    [Fact]
    public void Enforces_source_specific_provenance_and_asset_hash()
    {
        var reference = Valid("reference_crop") with
        {
            SourceReferenceSha256 = null,
            SourceBounds = null,
        };
        AssertInvalid(reference);

        var generated = Valid("generated_external") with { ProvenanceNote = null };
        AssertInvalid(generated);

        var wrongHash = Valid("user_file") with { AssetSha256 = new string('0', 64) };
        AssertInvalid(wrongHash);
    }

    public void Dispose()
    {
        if (File.Exists(_path))
            File.Delete(_path);
    }

    private RasterAssetDeclaration Valid(string sourceType)
    {
        var hash = Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(_path))).ToLowerInvariant();
        return new RasterAssetDeclaration(
            AssetId: "router-icon-1",
            SourceType: sourceType,
            RasterReason: "Complex small illustration is retained as one object.",
            SourceIsTightlyCropped: true,
            AtomicRasterUnit: true,
            ContainsReconstructableContent: false,
            DecompositionNote: "Text, border and connectors were rebuilt as Visio objects.",
            EditableScope: "object_only",
            SourceReferenceSha256: sourceType == "reference_crop" ? new string('a', 64) : null,
            SourceBounds: sourceType == "reference_crop" ? new PixelBox(12, 20, 80, 60) : null,
            AssetSha256: hash,
            SemanticRole: "wireless_router",
            ProvenanceNote: sourceType == "generated_external" ? "Generated by the host outside this plugin." : null);
    }

    private void AssertInvalid(RasterAssetDeclaration declaration)
    {
        var error = Assert.Throws<BridgeCommandException>(() =>
            RasterDeclarationValidator.Validate(
                _path,
                new PixelBox(0, 0, 64, 64),
                declaration));
        Assert.Equal(BridgeErrorCodes.RasterDeclarationInvalid, error.Code);
    }
}
